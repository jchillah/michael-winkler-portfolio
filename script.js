const languageToggle = document.getElementById("languageToggle");
const menuButton = document.getElementById("menuButton");
const mobileNav = document.getElementById("mobileNav");
const year = document.getElementById("year");

let language = localStorage.getItem("portfolio-language") || "de";

function applyLanguage(nextLanguage) {
  language = translations[nextLanguage] ? nextLanguage : "de";
  document.documentElement.lang = language;
  localStorage.setItem("portfolio-language", language);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  document.querySelectorAll("[data-lang-label]").forEach((element) => {
    element.classList.toggle("active", element.dataset.langLabel === language);
  });

  languageToggle.setAttribute(
    "aria-label",
    language === "de" ? "Sprache auf Englisch wechseln" : "Switch language to German"
  );
}

languageToggle?.addEventListener("click", () => {
  applyLanguage(language === "de" ? "en" : "de");
});

function setMenu(open) {
  const isOpen = Boolean(open);
  menuButton?.setAttribute("aria-expanded", String(isOpen));
  if (mobileNav) mobileNav.hidden = !isOpen;
  document.body.classList.toggle("menu-open", isOpen);
}

menuButton?.addEventListener("click", () => {
  const current = menuButton.getAttribute("aria-expanded") === "true";
  setMenu(!current);
});

mobileNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 980) setMenu(false);
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

if (year) {
  year.textContent = String(new Date().getFullYear());
}

applyLanguage(language);
